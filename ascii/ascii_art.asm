section .bss
    repeat_char resb 1

section .text
    global _start

_start:
    ;To Print the Betty Boop ASCII Art.
    mov ecx, art
    mov edx, art_len
    call print_string

    ; To print the repeated dashes using a loop.
    mov al, '-'
    mov ecx, 30
    call print_repeat

    ; To exit program.
    mov eax, 1
    xor ebx, ebx
    int 0x80


; --------------------------------
; print_string procedure
; ECX = address of string
; EDX = length of string
; --------------------------------
print_string:
    push eax
    push ebx

    mov eax, 4
    mov ebx, 1
    int 0x80

    pop ebx
    pop eax
    ret


; --------------------------------
; print_repeat procedure
; AL = character to print
; ECX = number of repetitions
; --------------------------------
print_repeat:
    push eax
    push ebx
    push ecx
    push edx
    push esi

    mov [repeat_char], al
    mov esi, ecx

repeat_loop:
    mov eax, 4
    mov ebx, 1
    mov ecx, repeat_char
    mov edx, 1
    int 0x80

    dec esi
    jnz repeat_loop

    pop esi
    pop edx
    pop ecx
    pop ebx
    pop eax
    ret